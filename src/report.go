package main

// The configuration report: a PDF listing what is configured in SFTPGo
// (users, groups, virtual folders, administrators, roles, event actions and
// rules) plus the removable drives mlw-storage manages. Everything is read
// through the SFTPGo API with the signed-in administrator's token. Secrets
// (passwords, keys, TOTP and recovery codes, secret payloads) are never
// written to the report.

import (
	"fmt"
	"log"
	"net/http"
	"net/url"
	"sort"
	"strconv"
	"strings"
	"time"
)

const reportPage = 100

// reportSection is one SFTPGo collection in the report.
type reportSection struct {
	Title, Path, Name string // Name is the field that identifies an item
}

var reportSections = []reportSection{
	{"Users", "/users", "username"},
	{"Groups", "/groups", "name"},
	{"Virtual folders", "/folders", "name"},
	{"Administrators", "/admins", "username"},
	{"Roles", "/roles", "name"},
	{"Event actions", "/eventactions", "name"},
	{"Event rules", "/eventrules", "name"},
}

// reportSkip names fields that hold secrets or only noise; they are left out.
var reportSkip = map[string]bool{
	"password": true, "payload": true, "key": true, "additional_data": true, "mode": true,
	"recovery_codes": true, "totp_config": true, "public_keys": true, "used_quota_size": true,
	"used_quota_files": true, "used_upload_data_transfer": true, "used_download_data_transfer": true,
	"last_quota_update": true, "created_at": true, "updated_at": true, "first_download": true,
	"first_upload": true, "last_password_change": true, "id": true,
}

func (u *ui) report(w http.ResponseWriter, r *http.Request) {
	s := u.session(r)
	if s == nil {
		http.Redirect(w, r, uiPrefix+"login", http.StatusFound)
		return
	}
	now := u.now().UTC()
	doc := newPDF("mlw-storage Configuration Report",
		"mlw-storage Configuration Report · "+now.Format("2006-01-02 15:04 UTC"))
	doc.heading("mlw-storage Configuration Report", 16)
	doc.text(0, "Generated: "+now.Format("2006-01-02 15:04:05 UTC"))
	doc.text(0, "Generated by: "+s.admin)
	var ver struct {
		Version string `json:"version"`
		Build   string `json:"build_date"`
	}
	if _, err := u.sfCall(s.token, http.MethodGet, "/version", nil, &ver); err == nil && ver.Version != "" {
		doc.text(0, "SFTPGo version: "+ver.Version)
	}
	doc.text(0, "Secrets such as passwords, keys and recovery codes are not included.")

	for _, sec := range reportSections {
		items, err := u.reportItems(s.token, sec.Path, sec.Name)
		switch {
		case err == errBadCredentials:
			u.endSession(w, r)
			http.Redirect(w, r, uiPrefix+"login?expired=1", http.StatusFound)
			return
		case err != nil:
			log.Printf("ui report: %s: %v", sec.Title, err)
			doc.heading(sec.Title, 13)
			doc.text(0, "Could not be read from SFTPGo.")
			continue
		}
		doc.heading(fmt.Sprintf("%s (%d)", sec.Title, len(items)), 13)
		if len(items) == 0 {
			doc.text(0, "None.")
		}
		for _, it := range items {
			head := fmt.Sprint(it[sec.Name])
			if sec.Path == "/users" || sec.Path == "/admins" {
				state := "Inactive"
				if st, _ := it["status"].(float64); st == 1 {
					state = "Active"
				}
				head += " (" + state + ")"
				delete(it, "status") // shown in the heading
			}
			doc.subheading(head)
			var lines []string
			flattenReport("", it, &lines)
			for _, l := range lines {
				doc.text(2, l)
			}
		}
	}
	if u.media != nil {
		doc.heading("Removable drives", 13)
		drives := u.media.snapshot()
		if len(drives) == 0 {
			doc.text(0, "None.")
		}
		for _, d := range drives {
			doc.subheading(d.Name)
			doc.text(2, "state: "+d.State)
			doc.text(2, fmt.Sprintf("mount point: %s  device: %s  type: %s  mounted: %t  manual: %t", d.MountPoint, d.Device, d.FSType, d.Mounted, d.Manual))
			if d.Size > 0 {
				doc.text(2, fmt.Sprintf("size: %.1f GB", float64(d.Size)/1e9))
			}
			if d.Admin != "" {
				doc.text(2, "decided by: "+d.Admin+" on "+d.Decided.UTC().Format("2006-01-02 15:04 UTC"))
			}
			doc.text(2, "sharing: "+describeShare(d.Share))
			if sh := d.Share; sh != nil {
				doc.text(2, "users: "+strings.Join(sh.Users, ", "))
				doc.text(2, "roles: "+strings.Join(sh.Roles, ", "))
			}
		}
	}

	w.Header().Set("Content-Type", "application/pdf")
	w.Header().Set("Content-Disposition", `attachment; filename="mlw-storage-report-`+now.Format("20060102-150405")+`.pdf"`)
	w.Header().Set("Cache-Control", "no-store")
	_, _ = w.Write(doc.bytes())
}

// reportItems reads every item of an SFTPGo collection, sorted by name.
func (u *ui) reportItems(token, path, name string) ([]map[string]any, error) {
	var all []map[string]any
	last := ""
	for offset := 0; offset < uiMaxUsers; offset += reportPage {
		q := url.Values{"limit": {fmt.Sprint(reportPage)}, "offset": {fmt.Sprint(offset)}, "order": {"ASC"}}
		var batch []map[string]any
		code, err := u.sfCall(token, http.MethodGet, path+"?"+q.Encode(), nil, &batch)
		if err != nil {
			return nil, err
		}
		if code == http.StatusNotFound || len(batch) == 0 {
			break
		}
		if first := fmt.Sprint(batch[0][name]); first == last { // endpoint ignores offset
			break
		} else {
			last = first
		}
		all = append(all, batch...)
		if len(batch) < reportPage {
			break
		}
	}
	sort.Slice(all, func(i, j int) bool {
		return strings.ToLower(fmt.Sprint(all[i][name])) < strings.ToLower(fmt.Sprint(all[j][name]))
	})
	return all, nil
}

// flattenReport turns a JSON object into "path: value" lines, skipping empty
// values and secrets.
func flattenReport(prefix string, v any, out *[]string) {
	switch x := v.(type) {
	case map[string]any:
		keys := make([]string, 0, len(x))
		for k := range x {
			if !reportSkip[k] {
				keys = append(keys, k)
			}
		}
		sort.Strings(keys)
		for _, k := range keys {
			p := k
			if prefix != "" {
				p = prefix + "." + k
			}
			flattenReport(p, x[k], out)
		}
	case []any:
		if len(x) == 0 {
			return
		}
		scalars := true
		for _, e := range x {
			switch e.(type) {
			case map[string]any, []any:
				scalars = false
			}
		}
		if scalars {
			parts := make([]string, len(x))
			for i, e := range x {
				parts[i] = fmt.Sprint(e)
			}
			*out = append(*out, prefix+": "+strings.Join(parts, ", "))
			return
		}
		for i, e := range x {
			flattenReport(fmt.Sprintf("%s[%d]", prefix, i), e, out)
		}
	case nil:
	case string:
		if x != "" {
			*out = append(*out, prefix+": "+x)
		}
	case float64:
		switch {
		case x == 0:
		case x > 1e11 && (strings.HasSuffix(prefix, "last_login") || strings.HasSuffix(prefix, "expiration_date")):
			*out = append(*out, prefix+": "+time.UnixMilli(int64(x)).UTC().Format("2006-01-02 15:04:05 UTC"))
		default:
			*out = append(*out, fmt.Sprintf("%s: %s", prefix, strconv.FormatFloat(x, 'f', -1, 64)))
		}
	case bool:
		if x {
			*out = append(*out, prefix+": true")
		}
	}
}
